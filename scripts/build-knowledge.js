const fs = require('fs');
const path = require('path');

const CRM_DIR = path.join(__dirname, '../crm');
const OUT_FILE = path.join(__dirname, '../supabase/functions/gemini-proxy/knowledge.ts');

const FILES_TO_INCLUDE = [
  'app.js',
  'modules/state.js',
  'utils.js'
];

function getAllFeatureFiles(dirPath) {
  const files = [];
  const entries = fs.readdirSync(dirPath, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.isFile() && entry.name.endsWith('.js')) {
      files.push(path.join('modules/features', entry.name));
    }
  }
  return files;
}

const featureFiles = getAllFeatureFiles(path.join(CRM_DIR, 'modules/features'));
const allFiles = [...FILES_TO_INCLUDE, ...featureFiles];

let knowledgeBaseText = 'SAFITRACK CRM SOURCE CODE AND KNOWLEDGE BASE:\n\n';

for (const relPath of allFiles) {
  const fullPath = path.join(CRM_DIR, relPath);
  if (fs.existsSync(fullPath)) {
    const content = fs.readFileSync(fullPath, 'utf8');
    knowledgeBaseText += `\n\n--- FILE: ${relPath} ---\n\n`;
    knowledgeBaseText += content;
  }
}

const tsContent = `// Auto-generated by scripts/build-knowledge.js
export const knowledgeBase = ${JSON.stringify(knowledgeBaseText)};
`;

const outDir = path.dirname(OUT_FILE);
if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

fs.writeFileSync(OUT_FILE, tsContent, 'utf8');
console.log('Successfully generated knowledge.ts');
